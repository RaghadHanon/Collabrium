using Application.Features.Reports.DTOs;
using QuestPDF.Fluent;
using QuestPDF.Helpers;
using QuestPDF.Infrastructure;

public class PdfService : IPdfService
{
    public byte[] GeneratePdf(CycleTimeReport data, byte[] chart1, byte[] chart2, byte[] chart3)
    {
        return Document.Create(container =>
        {
            container.Page(page =>
            {
                page.Margin(40);

                page.DefaultTextStyle(x =>
                    x.FontSize(10)
                     .FontColor("#2A3F58")
                     .FontFamily(Fonts.Courier));

                page.Header().Element(BuildHeader(data));

                page.Content().PaddingVertical(20).Column(col =>
                {
                    col.Spacing(30);

                    col.Item().Element(BuildKpiSection(data));

                    col.Item().Element(ChartSection("Cycle Time Performance", chart1));

                    col.Item().Row(row =>
                    {
                        row.Spacing(20);

                        row.RelativeItem()
                           .Element(ChartSection("Distribution Analysis", chart2));

                        row.RelativeItem()
                           .Element(ChartSection("Statistical Overview", chart3));
                    });

                    col.Item().Element(BuildTable(data));
                });

                page.Footer().AlignCenter().Text(text =>
                {
                    text.DefaultTextStyle(x => x.FontSize(9).FontColor("#9CA3AF"));
                    text.Span("Generated by Gemini Analytics Platform • ");
                    text.CurrentPageNumber();
                });
            });
        }).GeneratePdf();
    }

    private static Action<IContainer> BuildHeader(CycleTimeReport data)
    {
        return container =>
        {
            container.Column(col =>
            {
                col.Item().Text("Cycle Time Analytics Report")
                    .FontSize(28)
                    .Bold()
                    .FontColor("#2A3F58");

                col.Item().Row(row =>
                {
                    row.RelativeItem().Text($"Project: {data.ProjectKey}")
                        .FontSize(12)
                        .SemiBold();

                    row.RelativeItem().AlignRight()
                        .Text(data.GeneratedAt.ToString("dd MMM yyyy"));
                });
            });
        };
    }

    private static Action<IContainer> BuildKpiSection(CycleTimeReport data)
    {
        return container =>
        {
            container.Row(row =>
            {
                row.Spacing(15);

                row.RelativeItem().Component(new StatCard(
                    "Average Cycle Time",
                    $"{data.AverageCycleTimeDays:N1} days",
                    "#2A3F58"));

                row.RelativeItem().Component(new StatCard(
                    "Median Time",
                    $"{data.MedianCycleTimeDays:N1} days",
                    "#4A627D"));

                row.RelativeItem().Component(new StatCard(
                    "Max Time",
                    $"{data.MaxCycleTimeDays:N0} days",
                    "#ECBF28"));

                row.RelativeItem().Component(new StatCard(
                    "Items Analyzed",
                    $"{data.TotalItemsAnalyzed}",
                    "#9CA3AF"));
            });
        };
    }

    private static Action<IContainer> ChartSection(string title, byte[] image)
    {
        return container =>
        {
            container.Column(col =>
            {
                col.Item().Text(title)
                    .FontSize(16)
                    .Bold()
                    .FontColor("#2A3F58");

                col.Item().PaddingTop(10).Image(image);
            });
        };
    }

    private static Action<IContainer> BuildTable(CycleTimeReport data)
    {
        return container =>
        {
            container.Column(col =>
            {
                col.Item().Text("Detailed Work Item Analysis")
                    .FontSize(18)
                    .Bold();

                col.Item().PaddingTop(10).Table(table =>
                {
                    table.ColumnsDefinition(columns =>
                    {
                        columns.ConstantColumn(120);
                        columns.RelativeColumn();
                        columns.ConstantColumn(100);
                    });

                    table.Header(header =>
                    {
                        header.Cell().Text("Item Code").Bold();
                        header.Cell().Text("Completion Date").Bold();
                        header.Cell().AlignRight().Text("Cycle Time").Bold();
                    });

                    foreach (var item in data.Items)
                    {
                        table.Cell().Text(item.Code);
                        table.Cell().Text(item.EndDate.ToString("MMM dd yyyy"));
                        table.Cell().AlignRight().Text($"{item.CycleTimeDays} days");
                    }
                });
            });
        };
    }
}

public class StatCard : IComponent
{
    private readonly string _title;
    private readonly string _value;
    private readonly string _accentColor;

    public StatCard(string title, string value, string accentColor)
    {
        _title = title;
        _value = value;
        _accentColor = accentColor;
    }

    public void Compose(IContainer container)
    {
        container
            .Border(1)
            .BorderColor("#EFEFEF")
            .Padding(15)
            .Column(column =>
            {
                column.Item()
                    .Text(_title.ToUpper())
                    .FontSize(9)
                    .SemiBold()
                    .FontColor("#9CA3AF");

                column.Item()
                    .PaddingTop(5)
                    .Text(_value)
                    .FontSize(18)
                    .Bold()
                    .FontColor(_accentColor);
            });
    }
}